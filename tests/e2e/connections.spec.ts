import { test, expect } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';

test('Connections CRUD and real database verification', async ({ page }, testInfo) => {
  const suffix = `${testInfo.project.name}_${Date.now()}`;
  await page.goto('/connections');
  await expect(page.getByRole('heading', { name: 'Connections', exact: true })).toBeVisible();
  await expect(page.getByText('Backend available', { exact: true })).toBeVisible();
  for (const database of ['POSTGRESQL', 'MYSQL'] as const) {
    const code = `e2e_${database.toLowerCase()}_${suffix}`;
    const password = await readFile(`/run/aat-e2e/${database === 'MYSQL' ? 'mysql_etl' : 'pg_etl'}`, 'utf8');
    await page.getByRole('button', { name: 'Add connection', exact: true }).click();
    const form = page.getByRole('form', { name: 'Add connection' });
    await expect(form.getByRole('textbox', { name: 'Connection code', exact: true })).toBeFocused();
    await page.keyboard.press('Tab');
    await expect(form.getByRole('textbox', { name: 'Connection name', exact: true })).toBeFocused();
    await form.getByLabel('Connection code', { exact: true }).fill(code);
    await form.getByLabel('Connection name', { exact: true }).fill(`E2E ${database}`);
    await form.getByRole('combobox', { name: 'Database type', exact: true }).selectOption(database);
    await form.getByLabel('Database name', { exact: true }).fill('etl_test');
    await form.getByLabel('Username', { exact: true }).fill('aat_etl');
    await form.getByLabel('Password', { exact: true }).fill(password);
    await form.getByRole('button', { name: 'Save connection', exact: true }).click();
    await expect(page.getByText('Connection saved.', { exact: true })).toBeVisible();
    await page.getByRole('searchbox', { name: 'Search connections', exact: true }).fill(code);
    const row = page.getByRole('row').filter({ has: page.getByRole('button', { name: `View ${code}`, exact: true }) });
    await expect(row).toHaveCount(1);
    await row.getByRole('button', { name: `View ${code}`, exact: true }).click();
    await page.getByRole('button', { name: 'Test connection', exact: true }).click();
    await expect(page.getByText('Connection verified.', { exact: true })).toBeVisible({ timeout: 35_000 });
    await expect(row.getByText('Verified', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Edit connection', exact: true }).click();
    const edit = page.getByRole('form', { name: 'Edit connection' });
    await expect(edit.getByLabel('Password', { exact: true })).toHaveValue('');
    await edit.getByLabel('Connection name', { exact: true }).fill(`Updated ${database}`);
    await edit.getByRole('button', { name: 'Save connection', exact: true }).click();
    await expect(page.getByRole('heading', { name: `Updated ${database}`, exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Test connection', exact: true }).click();
    await expect(page.getByText('Connection verified.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Edit connection', exact: true }).click();
    await page.getByRole('form', { name: 'Edit connection' }).getByLabel('Password', { exact: true }).fill('intentionally-invalid-synthetic-password');
    await page.getByRole('button', { name: 'Save connection', exact: true }).click();
    await expect(page.getByText('Connection saved.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Test connection', exact: true }).click();
    await expect(page.getByRole('alert')).toContainText('Authentication failed', { timeout: 35_000 });
    await expect(row.getByText('Failed', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Delete connection', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Delete connection' })).toBeVisible();
    await expect(page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(row).toHaveCount(1);
    await page.getByRole('button', { name: 'Delete connection', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
    await expect(page.getByText('Connection deleted.', { exact: true })).toBeVisible();
    await expect(row).toHaveCount(0);
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await mkdir('/tmp/aat-e2e-artifacts', { recursive: true });
  await page.screenshot({ path: `/tmp/aat-e2e-artifacts/connections-${testInfo.project.name}.png`, fullPage: true });
});

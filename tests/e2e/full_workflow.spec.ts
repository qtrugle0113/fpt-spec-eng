import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
test.use({ actionTimeout: 15000 });

test('An operator creates a connection and table, loads the uploaded CSV, and follows the real run', async ({ page, request }, info) => {
  test.setTimeout(600000);
  const started = Date.now();
  const suffix = `${info.project.name}_${started}`;
  const code = `full_pg_${suffix}`;
  const table = `full_${suffix}`;
  const dag = `aat_full_${suffix}`;
  const folder = `/tmp/full-${suffix}`;
  await mkdir(folder, { recursive: true });
  const workbook = (kind: string, template: string, output: string, data: object) => execFileSync('python3',
    ['/tests/make_full_workflow.py', kind, template, output, JSON.stringify(data)],
    { env: { ...process.env, PYTHONPATH: '/tests/workbook-libs' }, timeout: 20000 });

  await page.goto('/connections');
  await page.getByRole('button', { name: 'Add connection', exact: true }).click();
  const form = page.getByRole('form', { name: 'Add connection' });
  await form.getByLabel('Connection code', { exact: true }).fill(code);
  await form.getByLabel('Connection name', { exact: true }).fill(`Full ${suffix}`);
  await form.getByLabel('Database name', { exact: true }).fill('etl_test');
  await form.getByLabel('Username', { exact: true }).fill('aat_etl');
  await form.getByLabel('Password', { exact: true }).fill(await readFile('/run/aat-e2e/pg_etl', 'utf8'));
  const saved = page.waitForResponse(r => r.url().endsWith('/api/v1/connections') && r.request().method() === 'POST');
  await form.getByRole('button', { name: 'Save connection', exact: true }).click();
  const connection = await (await saved).json();
  await page.getByRole('searchbox', { name: 'Search connections', exact: true }).fill(code);
  await page.getByRole('button', { name: `View ${code}`, exact: true }).click();
  await page.getByRole('button', { name: 'Test connection', exact: true }).click();
  await expect(page.getByText('Connection verified.', { exact: true })).toBeVisible({ timeout: 35000 });

  await page.goto('/tables');
  const tableDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download Table Definition template' }).click();
  await (await tableDownload).saveAs(`${folder}/table-template.xlsx`);
  workbook('table', `${folder}/table-template.xlsx`, `${folder}/table.xlsx`, { code, table });
  await page.getByLabel('Table Definition workbook', { exact: true }).setInputFiles(`${folder}/table.xlsx`);
  const tableUploaded = page.waitForResponse(r => r.url().endsWith('/api/v1/definition-uploads') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Upload workbook', exact: true }).click();
  const tableUpload = await (await tableUploaded).json();
  await page.getByRole('combobox', { name: 'Target connection', exact: true }).selectOption(connection.id);
  await page.getByRole('button', { name: 'Validate workbook', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review tables', exact: true })).toBeVisible({ timeout: 35000 });
  await page.getByRole('checkbox', { name: 'I reviewed the target tables and generated SQL.' }).check();
  const tableCreated = page.waitForResponse(r => r.url().endsWith('/api/v1/table-creation-jobs') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Confirm and create tables', exact: true }).click();
  const tableOperation = await (await tableCreated).json();
  await expect(page.getByText('Operation: SUCCEEDED', { exact: true })).toBeVisible({ timeout: 35000 });

  await page.goto('/dag-builder');
  const source = await readFile('/tests/full-customers.csv');
  const uploadForm = page.getByRole('form', { name: 'Upload source file', exact: true });
  await uploadForm.getByLabel('Source file', { exact: true }).setInputFiles({ name: `${suffix}.csv`, mimeType: 'text/csv', buffer: source });
  const uploaded = page.waitForResponse(r => r.url().endsWith('/api/v1/files') && r.request().method() === 'POST');
  await uploadForm.getByRole('button', { name: 'Upload source file', exact: true }).click();
  const file = await (await uploaded).json();
  expect(file.sha256).toBe(createHash('sha256').update(source).digest('hex'));
  const details = page.getByRole('region', { name: 'Source file details', exact: true });
  await details.getByRole('button', { name: 'Preview with these settings', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Source data preview', exact: true })).toContainText('Nguyễn, An');
  await details.getByRole('button', { name: 'Validate full file', exact: true }).click();
  await expect(details.getByRole('heading', { name: 'Validation: SUCCEEDED', exact: true })).toBeVisible({ timeout: 35000 });
  await details.getByRole('button', { name: 'Select as ETL source', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Selected ETL source', exact: true })).toContainText(file.id);
  const etlDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download ETL Definition template' }).click();
  await (await etlDownload).saveAs(`${folder}/etl-template.xlsx`);
  workbook('etl', `${folder}/etl-template.xlsx`, `${folder}/etl.xlsx`, { code, table, dag, file: file.id });
  await page.getByLabel('ETL Definition workbook', { exact: true }).setInputFiles(`${folder}/etl.xlsx`);
  const etlUploaded = page.waitForResponse(r => r.url().endsWith('/api/v1/definition-uploads') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Upload ETL workbook', exact: true }).click();
  const etlUpload = await (await etlUploaded).json();
  await page.getByRole('button', { name: 'Validate ETL workbook', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Review schedules and load policies' })).toBeVisible({ timeout: 45000 });
  await page.getByRole('button', { name: 'Review schedules and load policies' }).click();
  const support = page.getByRole('checkbox', { name: 'I reviewed and authorize creating the displayed support objects in the target database.' });
  if (await support.count()) await support.check();
  await page.getByRole('checkbox', { name: 'I reviewed every selected source, target, mapping, schedule and load policy. Deploy these exact revisions.' }).check();
  await page.getByRole('button', { name: 'Confirm and deploy workflows', exact: true }).click();
  const deployment = page.getByRole('article', { name: 'Deployment result for ' + dag });
  await expect(deployment.getByText('DEPLOYED', { exact: true })).toBeVisible({ timeout: 150000 });
  const popupEvent = page.waitForEvent('popup');
  await deployment.getByRole('link', { name: 'Open Airflow', exact: true }).click();
  const popup = await popupEvent;
  await popup.waitForLoadState('domcontentloaded');
  expect(new URL(popup.url()).origin).toBe(process.env.AIRFLOW_EXPECTED_ORIGIN ?? 'http://airflow-apiserver:8080');
  await expect(popup).toHaveTitle(/Airflow/i);
  await popup.close();
  await deployment.getByRole('checkbox', { name: /I confirm the schedule state change/ }).check();
  await deployment.getByRole('button', { name: 'Enable manual execution', exact: true }).click();
  await expect(page.getByText(/State command succeeded/)).toBeVisible({ timeout: 30000 });
  await deployment.getByRole('checkbox', { name: /I confirm a new manual run/ }).check();
  const trigger = page.waitForResponse(r => r.url().endsWith('/trigger') && r.request().method() === 'POST');
  await deployment.getByRole('button', { name: 'Run workflow now', exact: true }).click();
  const command = await (await trigger).json();
  const run = 'manual__aat_' + command.id;
  await expect(page.getByText(/Manual trigger succeeded/)).toBeVisible({ timeout: 30000 });
  await page.goto('/monitoring?dag=' + dag);
  const workflow = page.getByRole('region', { name: 'Workflow details', exact: true });
  const row = workflow.getByRole('row').filter({ hasText: run });
  await expect(row.getByRole('cell', { name: 'success', exact: true })).toBeVisible({ timeout: 130000 });
  await row.getByRole('button', { name: 'View run details', exact: true }).click();
  const evidence = page.getByRole('region', { name: 'Run details', exact: true });
  await expect(evidence.locator('dt').filter({ hasText: /^Loaded rows$/ }).locator('xpath=following-sibling::dd[1]')).toHaveText('4');
  await page.goto('/');
  await page.getByRole('button', { name: 'Refresh dashboard' }).click();
  await expect(page.getByRole('row').filter({ hasText: run }).getByRole('cell', { name: 'success', exact: true })).toBeVisible({ timeout: 30000 });
  expect(Date.now() - started).toBeLessThan(600000);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const artifact = '/tmp/aat-e2e-artifacts/full-workflows.json';
  await mkdir('/tmp/aat-e2e-artifacts', { recursive: true });
  let previous: object[] = [];
  try { previous = JSON.parse(await readFile(artifact, 'utf8')); } catch { /* First owned browser fixture. */ }
  await writeFile(artifact, JSON.stringify([...previous, { dag, run, code, table, file: file.id, file_name: file.file_name,
    checksum: file.sha256, etl_upload: etlUpload.id, table_upload: tableUpload.id,
    table_job: tableOperation.result_links[0].split('/').pop(), elapsed_ms: Date.now() - started }]));
});

@dataclass
class Compiled:
    config:ETLConfig
    source_hash:str
    target_hash:str
    dependency:dict
    warnings:list[str]
    support_ddl:list[str]
    columns:list[dict]
    primary_key:list[str]


def connection_revision(session,code):
    connection=session.scalar(select(Connection).where(func.lower(Connection.code)==code.strip().lower(),Connection.deleted_at.is_(None)))
    if connection is None:raise APIError('EXCEL_REFERENCE_NOT_FOUND','A referenced connection does not exist.',409)
    _,revision=active(session,connection.id)
    if revision.test_status!='SUCCESS' or not revision.physical_server_fingerprint:
        raise APIError('CONNECTION_NOT_VERIFIED','Test every referenced connection first.',409)
    return revision


def schema(revision,value):
    if revision.database_type=='MYSQL':
        if value not in (None,revision.database_name):raise APIError('INVALID_SCHEMA','MySQL schema must match Database Name.',422)
        return revision.database_name
    return value or revision.schema_name or 'public'


def literal(value,profile):
    logical=profile['logical_type']
    if isinstance(value,Decimal):value=str(value)
    if logical=='decimal' and type(value) is int:value=str(value)
    return TypedLiteral.model_validate(dict(logical_type=logical,value=value)).model_dump(mode='json')


def confirmation_scope(upload_id,sha256,identities):
    # Bind all 100 supported DAG revisions without exceeding the signer's
    # bounded token size. Hashes cover the full ordered revision/dependency set.
    return dict(upload_id=str(upload_id),sha256=sha256,revision_set_sha256=digest(identities))


def sample(profile):
    return {'integer':1,'bigint':1,'boolean':True,'decimal':Decimal('0'),'varchar':'x','text':'x',
        'date':date(2020,1,1),'timestamp':datetime(2020,1,1,tzinfo=timezone.utc if profile.get('timezone_semantics')=='aware' else None)}[profile['logical_type']]


def public_columns(reflected,profiles,primary,dialect):
    columns=[];warnings=[]
    for ordinal,column in enumerate(reflected,1):
        profile=profiles.get(column['name'])
        if profile is None:
            try:profile=column_profile(column,dialect)
            except ValueError:
                warnings.append('Unmapped target column '+column['name']+' has an unsupported type and will not be written.');continue
        value={key:profile[key] for key in ('name','logical_type','nullable','has_default','length','precision','scale') if key in profile}
        value.update(ordinal=ordinal,primary_key_ordinal=primary.index(column['name'])+1 if column['name'] in primary else None)
        if profile.get('generated'):warnings.append('Target column '+column['name']+' is generated by the database.')
        if profile['has_default']:
            expression=str(column['default']);match=re.fullmatch(r"'((?:[^']|'')*)'(?:::[A-Za-z_ ]+(?:\(\d+(?:,\d+)?\))?)?",expression)
            raw=match.group(1).replace("''", "'") if match and '\\' not in expression else expression
            logical=profile['logical_type']
            try:
                if logical in ('integer','bigint'):
                    if not re.fullmatch(r'[+-]?\d+',raw):raise ValueError()
                    raw=int(raw)
                elif logical=='boolean':
                    if raw.lower() not in ('true','false','1','0'):raise ValueError()
                    raw=raw.lower() in ('true','1')
                elif logical in ('varchar','text') and match is None:raise ValueError()
                elif logical=='timestamp':raw=datetime.fromisoformat(raw).isoformat()
                value['default_literal']=literal(raw,profile)
            except (ValueError,TypeError):
                warnings.append('Target column '+column['name']+' has a server default expression; it is preserved and not evaluated in preview.')
                continue
        columns.append(value)
    return columns,warnings


def permissions(engine,profile,*,strategy=None):
    with engine.connect() as connection:
        table=Table(profile.table,MetaData(),schema=profile.schema,autoload_with=connection)
        # A zero-row query checks actual read access without exposing user rows.
        connection.execute(select(*(table.c[c['name']] for c in profile.columns)).where(false())).close()
        if strategy is None:return
        needed={'INSERT'}
        if strategy=='UPSERT':needed.add('UPDATE')
        if strategy=='FULL_REFRESH':needed.add('DELETE')
        if connection.dialect.name=='postgresql':
            quoted=connection.dialect.identifier_preparer.quote_schema(profile.schema)+'.'+connection.dialect.identifier_preparer.quote(profile.table)
            for privilege in needed:
                if not connection.scalar(text('SELECT has_table_privilege(current_user,:table,:privilege)'),{'table':quoted,'privilege':privilege}):
                    raise APIError('TARGET_NOT_WRITABLE','Target permissions do not allow the selected load strategy.',409)
        else:
            from aat_etl.loaders.privileges import mysql_permissions
            granted=mysql_permissions(connection.exec_driver_sql('SHOW GRANTS').scalars(),profile.schema,profile.table)
            if not needed<=granted:raise APIError('TARGET_NOT_WRITABLE','Target permissions do not allow the selected load strategy.',409)


def compile_definition(spec):
    value=spec.values
    with transaction() as session:
        target=connection_revision(session,value['target_connection_code'])
        target_ref=dict(connection_revision_id=str(target.id),schema=schema(target,value['target_schema']),table=value['target_table'])
        dependency={'target_revision_id':str(target.id),'target_server':target.physical_server_fingerprint}
        if value['source_type']=='DB':
            source=connection_revision(session,value['source_connection_code'])
            source_ref=dict(type='DB',connection_revision_id=str(source.id),schema=schema(source,value['source_schema']),table=value['source_table'])
            dependency.update(source_revision_id=str(source.id),source_server=source.physical_server_fingerprint)
        else:
            from aat_api.services import files
            from aat_etl.readers.file_source import FileReference
            file=files.require(session,UUID(value['source_file_id']))
            if files.expired(file) or file.validation_status!='VALID':raise APIError('FILE_NOT_VALID','Validate the unexpired source file first.',409)
            parser=files.current_parser(session,file);file_type='CSV' if file.extension=='.csv' else 'TXT'
            if value['source_type'] not in ('FILE',file_type):raise APIError('FILE_TYPE_MISMATCH','Source Type does not match the file reference.',422)
            source_ref=dict(type=file_type,file_id=str(file.id),parser_revision=parser.revision,file_sha256=file.sha256)
            reference=FileReference(file.id,parser.revision,file.sha256,file.bytes,files.source_path(file.safe_storage_key),files.parser_public(parser))
            dependency.update(file_id=str(file.id),file_sha256=file.sha256,parser_id=str(parser.id),parser_revision=parser.revision)
    with ExitStack() as owned:
        target_engine_=owned.enter_context(target_engine(UUID(target_ref['connection_revision_id'])))
        inspector=inspect(target_engine_)
        if not inspector.has_table(target_ref['table'],schema=target_ref['schema']):
            raise APIError('TARGET_TABLE_MISSING','Create the target in Table Management before validating this ETL workbook.',409)
        target_columns=inspector.get_columns(target_ref['table'],schema=target_ref['schema'])
        enabled=[mapping for mapping in spec.mappings if mapping['enabled']]
        target_names={mapping['target_column'] for mapping in enabled}
        if source_ref['type']=='DB':
            source_engine=owned.enter_context(target_engine(UUID(source_ref['connection_revision_id'])))
            source_columns=inspect(source_engine).get_columns(source_ref['table'],schema=source_ref['schema'])
            if not enabled:target_names={c['name'] for c in target_columns}&{c['name'] for c in source_columns}
            used_sources={mapping['source_column'] for mapping in enabled if mapping['source_column'] is not None} if enabled else target_names
            used_sources=set(used_sources)|{predicate['column'] for predicate in value.get('filter',{}).get('and',[])}
            source_profiles={c['name']:column_profile(c,source_engine.dialect.name) for c in source_columns if c['name'] in used_sources}
        elif not enabled:
            # Header inspection derives the implicit intersection in the engine;
            # default literals only need profiles for explicitly enabled mappings.
            target_names=set()
        target_profiles={c['name']:column_profile(c,target_engine_.dialect.name) for c in target_columns if c['name'] in target_names}
        mappings=[]
        for mapping in enabled:
            target_profile=target_profiles.get(mapping['target_column'])
            if target_profile is None:raise APIError('MAPPING_TARGET_MISSING','A mapped target column does not exist.',409)
            item={k:mapping[k] for k in ('source_column','target_column','transformation','enabled') if mapping[k] is not None}
            if mapping['default_json'] is not None:
                item['default_literal']=literal(json.loads(mapping['default_json'],parse_float=Decimal),target_profile)
            mappings.append(item)
        config={k:value[k] for k in ('dag_id','schedule','timezone','catchup','is_paused','load_strategy','conflict_keys','batch_size','retry_count','retry_delay')}
        if value['start_date'] is not None:config['start_date']=value['start_date']
        config.update(source=source_ref,target={**target_ref,'physical_target_id':'0'*64},mappings=mappings)
        if value.get('filter'):
            predicates=[]
            for predicate in value['filter']['and']:
                profile=source_profiles.get(predicate['column'])
                if profile is None:raise APIError('FILTER_COLUMN_MISSING','A filtered source column does not exist.',409)
                item={k:v for k,v in predicate.items() if k!='value'}
                if 'value' in predicate:
                    item['value']=[literal(v,profile) for v in predicate['value']] if predicate['operator']=='IN' else literal(predicate['value'],profile)
                predicates.append(item)
            config['filter']={'and':predicates}
        config=ETLConfig.model_validate(config)
        if source_ref['type']=='DB':source_schema,target_schema=inspect_inputs(config,source_engine,target_engine_)
        else:
            from aat_etl.readers.file_source import inspect_file_inputs
            try:
                source_schema,target_schema=inspect_file_inputs(config,reference,target_engine_)
            except OSError:
                raise APIError('FILE_SOURCE_UNAVAILABLE','Source file is unavailable. Upload and validate a new source file.',409) from None
        if source_ref['type']=='DB':
            preflight(source_schema,target_schema,expected_source_hash=source_schema.fingerprint,expected_target_hash=target_schema.fingerprint,
                expected_source_identity=source_schema.physical_identity,expected_target_identity=target_schema.physical_identity)
        config=config.model_copy(update={'target':config.target.model_copy(update={'physical_target_id':target_schema.physical_identity})})
        permissions(target_engine_,target_schema,strategy=config.load_strategy)
        if source_ref['type']=='DB':permissions(source_engine,source_schema)
        if config.load_strategy=='UPSERT' and not any(key['columns']==config.conflict_keys and key.get('predicate') is None for key in target_schema.keys):
            raise APIError('CONFLICT_KEY_INVALID','Conflict Key must match an unconditional target primary or unique key.',409)
        # Validate the mapping's static type route with synthetic typed values;
        # real rows still receive full runtime value validation.
        if config.mappings:
            sources={c['name']:c for c in source_schema.columns};targets={c['name']:c for c in target_schema.columns}
            for mapping in config.mappings:
                if mapping.transformation!='CONSTANT' and mapping.source_column not in sources:
                    raise APIError('MAPPING_SOURCE_MISSING','A mapped source column does not exist.',409)
                row={name:sample(profile) for name,profile in sources.items()}
                if mapping.transformation=='TYPE_CONVERSION' and sources[mapping.source_column]['logical_type'] in ('text','varchar'):
                    probe_value=sample(targets[mapping.target_column])
                    row[mapping.source_column]=probe_value.isoformat() if isinstance(probe_value,(date,datetime)) else str(probe_value).lower() if type(probe_value) is bool else str(probe_value)
                map_row(row,source_schema=source_schema.columns,target_schema=[targets[mapping.target_column]],mappings=[mapping])
                if mapping.transformation=='NULL_HANDLING':
                    row[mapping.source_column]=None
                    map_row(row,source_schema=source_schema.columns,target_schema=[targets[mapping.target_column]],mappings=[mapping])
        else:map_row({c['name']:sample(c) for c in source_schema.columns},source_schema=source_schema.columns,target_schema=target_schema.columns,mappings=[])
        warnings=['New DAGs remain paused until activation is confirmed.'] if spec.requested_enabled else []
        if source_ref['type']=='DB':
            ignored=sorted({c['name'] for c in source_columns}-{c['name'] for c in source_schema.columns})
            if ignored:warnings.append('Unmapped source columns will be ignored: '+', '.join(ignored)+'.')
        if config.load_strategy=='APPEND':warnings.append('APPEND runs may add duplicate data; prior committed batches remain after a later error.')
        if config.load_strategy=='FULL_REFRESH':
            try:
                with TargetSession(target_engine_,schema=config.target.schema_,table=config.target.table,timeout=0) as session:check_dependencies(session)
            except TargetBusy:raise APIError('TARGET_BUSY','Target is busy. Retry the preview after the current operation finishes.',409,True) from None
            warnings.extend(['FULL_REFRESH requires a separate scoped replacement authorization.','Empty replacement requires a separate explicit acknowledgment.'])
        ledger=TargetLedger(target_engine_.dialect.name,config.target.schema_)
        ddl=([str(CreateSchema('_aat_control',if_not_exists=True).compile(dialect=target_engine_.dialect))] if target_engine_.dialect.name=='postgresql' else [])
        ddl.extend(str(CreateTable(table).compile(dialect=target_engine_.dialect)) for table in ledger.metadata.sorted_tables)
        with target_engine_.connect() as c:
            existing=inspect(c)
            if any(existing.has_table(table.name,schema=table.schema) for table in ledger.metadata.sorted_tables):
                ensure_support(c,schema=config.target.schema_,consent=False)
                ddl=[]
        dependency.update(source_schema=source_schema.fingerprint,target_schema=target_schema.fingerprint)
        primary=inspector.get_pk_constraint(config.target.table,schema=config.target.schema_).get('constrained_columns') or []
        profiles={profile['name']:profile for profile in target_schema.columns}
        columns,column_warnings=public_columns(target_columns,profiles,primary,target_engine_.dialect.name)
        warnings.extend(column_warnings)
        return Compiled(config,source_schema.fingerprint,target_schema.fingerprint,dependency,warnings,ddl,columns,primary)


def preview(upload_id):
    with transaction() as session:
        upload=uploads.require(session,upload_id)
        if upload.kind!='ETL' or upload.status!='VALIDATED':raise APIError('PREVIEW_UNAVAILABLE','Validate the ETL Definition workbook first.',409)
        revisions=session.scalars(select(ETLDefinitionRevision).where(ETLDefinitionRevision.upload_id==upload_id).order_by(ETLDefinitionRevision.created_at,ETLDefinitionRevision.id)).all()
        if not revisions:raise APIError('PREVIEW_UNAVAILABLE','No validated ETL definitions are available.',409)
        parents={revision.definition_id:session.get(ETLDefinition,revision.definition_id).current_revision_id for revision in revisions}
        prior={identity:session.get(ETLDefinitionRevision,identity).config_json for identity in parents.values() if identity}
        from aat_api.validation.etl_definitions import validate
        file=session.get(uploads.UploadedFile,upload.uploaded_file_id)
        path=uploads.storage()/file.safe_storage_key;expected=upload.workbook_sha256
    import hashlib
    if hashlib.sha256(path.read_bytes()).hexdigest()!=expected:raise APIError('CHECKSUM_MISMATCH','Workbook checksum changed.',409)
    parsed=validate(path)
    if parsed.issues:raise APIError('WORKBOOK_INVALID','Workbook cannot be previewed.',409)
    specs={spec.values['dag_id']:spec for spec in parsed.definitions};items=[];identities=[];dependencies=[]
    for revision in revisions:
        spec=specs[revision.config_json['dag_id']]
        # A blank workbook cell resolves once at validation, never against a
        # later workspace default when reviewing an immutable revision.
        if spec.batch_defaulted:spec.values['batch_size']=revision.config_json['batch_size']
        compiled=compile_definition(spec)
        if compiled.config.model_dump(mode='json',by_alias=True,exclude_none=True)!=revision.config_json or digest(compiled.dependency)!=revision.dependency_fingerprint:
            raise APIError('DEPENDENCY_CHANGED','ETL dependencies changed. Validate a new workbook.',409)
        dependencies.append(compiled.dependency)
        current=parents[revision.definition_id]
        if current and current!=revision.id:
            changed=sorted(key for key in set(prior[current])|set(revision.config_json) if prior[current].get(key)!=revision.config_json.get(key))
            compiled.warnings.append('Existing managed DAG requires a paused revision deployment.')
            if changed:compiled.warnings.append('Changed configuration fields: '+', '.join(changed)+'.')
        items.append(dict(id=str(revision.id),definition_id=str(revision.definition_id),target=compiled.config.target.schema_+'.'+compiled.config.target.table,
            config=revision.config_json,support_ddl=compiled.support_ddl,warnings=compiled.warnings,columns=compiled.columns,primary_key=compiled.primary_key))
        identities.append(dict(id=str(revision.id),config_sha256=revision.config_sha256,dependency_fingerprint=revision.dependency_fingerprint,
            previous_revision_id=str(current) if current else None))
    from aat_api.services.etl_validation import recheck_dependencies
    with transaction() as session:
        for dependency in dependencies:recheck_dependencies(session,dependency)
        for definition_id,previous in parents.items():
            if session.get(ETLDefinition,definition_id).current_revision_id!=previous:
                raise APIError('DEPENDENCY_CHANGED','DAG revision changed during preview.',409)
    scope=confirmation_scope(upload_id,expected,identities)
    now=int(datetime.now(timezone.utc).timestamp())
    return dict(upload_id=str(upload_id),items=items,confirmation_token=signer().issue(scope,now=now),
        expires_at=datetime.fromtimestamp(now,timezone.utc)+timedelta(seconds=600),dependency_fingerprint=digest(scope))
